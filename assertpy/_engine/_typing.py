        # these three pivot to the exception they found; a bare `type` names none, and ty refused it against the bound
        @overload
        def caused_by(self, ex: type[_Landed]) -> _InvokedAssertion[_Landed]: ...
        # the cause is read with `isinstance`, so a union or a tuple of classes is taken, landing on no one class
        @overload
        def caused_by(self, ex: ClassInfo) -> _InvokedAssertion[BaseException]: ...
        def errors(self) -> _ListAssertion[BaseException]: ...
        @overload
        def error_of(self, ex: type[_Landed]) -> _InvokedAssertion[_Landed]: ...
        @overload
        def error_of(self, ex: type) -> _InvokedAssertion[BaseException]: ...
        def does_not_contain_error(self, *ex_types: type | ExceptionInfo) -> Self: ...
        @overload
        def has_root_cause(self, ex: type[_Landed]) -> _InvokedAssertion[_Landed]: ...
        @overload
        def has_root_cause(self, ex: ClassInfo) -> _InvokedAssertion[BaseException]: ...
        def contains_error(self, *ex_types: type | ExceptionInfo) -> Self: ...
        # a `list` is a subgroup, so the entry type is recursive; spelled with `Any` inside because a
        # recursive alias declared here is what ty reads as `Any` anyway, measured in `_typing.py`'s own
        # history, and naming it would suggest a precision the checkers do not carry
        def matches_error_tree(self, *expected: type | list[Any]) -> Self: ...

